package fields

import (
	"testing"

	"github.com/dejitarudemon/axidb-go-protocol/v1/internal/testutil"
)

func TestKey(t *testing.T) {
	tests := []struct {
		name string
		k    Key
		want []byte
	}{
		{"nil", Key(nil), nil},
		{"empty", Key([]byte{}), []byte{}},
		{"4 bytes", Key([]byte{0xFF, 0xFF, 0xFF, 0xFF}), []byte{0xFF, 0xFF, 0xFF, 0xFF}},
		{
			"16 bytes",
			Key([]byte{0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF}),
			[]byte{0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			testutil.AssertEncoded(t, tt.k, tt.want)
		})
	}
}
