func TestUnauthorized_Size(t *testing.T) {
	tests := []struct {
		e    ErrorUnauthorized
		want int
	}{
		{ErrorUnauthorized{nil, generateNewTracebackID()}, 18},
		{ErrorUnauthorized{[]byte{}, generateNewTracebackID()}, 18},
		{ErrorUnauthorized{[]byte{0x01, 0x02}, generateNewTracebackID()}, 18},
		{ErrorUnauthorized{[]byte("192.168.1.1"), generateNewTracebackID()}, 18},
		{ErrorUnauthorized{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

