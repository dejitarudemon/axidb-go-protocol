func TestRestrictedRequest_Size(t *testing.T) {
	tests := []struct {
		e    ErrorRestrictedRequest
		want int
	}{
		{ErrorRestrictedRequest{nil, nil, nil, command.Handshake, 0, generateNewTracebackID()}, 18},
		{ErrorRestrictedRequest{[]byte{}, nil, nil, command.Answer, 0, generateNewTracebackID()}, 18},
		{ErrorRestrictedRequest{nil, []byte{}, nil, command.Read, 0, generateNewTracebackID()}, 18},
		{ErrorRestrictedRequest{nil, nil, []byte{}, command.Write, 0, generateNewTracebackID()}, 18},
		{ErrorRestrictedRequest{[]byte("user"), []byte("192.168.1.1"), []byte("key"), command.Delete, 1, generateNewTracebackID()}, 18},
		{ErrorRestrictedRequest{[]byte("user"), []byte("192.168.1.1"), []byte("key"), command.Delete, math.MaxUint32, generateNewTracebackID()}, 18},
		{ErrorRestrictedRequest{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

