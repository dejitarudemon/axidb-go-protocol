func TestBodyLimitIsExceeded_Size(t *testing.T) {
	tests := []struct {
		e    ErrorBodyLimitIsExceeded
		want int
	}{
		{ErrorBodyLimitIsExceeded{0, 1, generateNewTracebackID()}, 22},
		{ErrorBodyLimitIsExceeded{1, 0, generateNewTracebackID()}, 22},
		{ErrorBodyLimitIsExceeded{1, 1, generateNewTracebackID()}, 22},
		{ErrorBodyLimitIsExceeded{1, math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorBodyLimitIsExceeded{math.MaxUint32, 1, generateNewTracebackID()}, 22},
		{ErrorBodyLimitIsExceeded{math.MaxUint32, math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorBodyLimitIsExceeded{}, 22},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

