func TestUnexpectedCommandInBatch_Size(t *testing.T) {
	tests := []struct {
		e    ErrorUnexpectedCommandInBatch
		want int
	}{
		{ErrorUnexpectedCommandInBatch{command.Answer, 0, generateNewTracebackID()}, 22},
		{ErrorUnexpectedCommandInBatch{command.Batch, 1, generateNewTracebackID()}, 22},
		{ErrorUnexpectedCommandInBatch{command.Handshake, math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorUnexpectedCommandInBatch{command.Code(10), 1, generateNewTracebackID()}, 22},
		{ErrorUnexpectedCommandInBatch{command.Code(11), math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorUnexpectedCommandInBatch{command.Code(255), math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorUnexpectedCommandInBatch{}, 22},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

