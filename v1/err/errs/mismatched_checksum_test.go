func TestMismatchedChecksum_Size(t *testing.T) {
	tests := []struct {
		e    ErrorMismatchedChecksum
		want int
	}{
		{ErrorMismatchedChecksum{0, 1, generateNewTracebackID()}, 18},
		{ErrorMismatchedChecksum{1, 0, generateNewTracebackID()}, 18},
		{ErrorMismatchedChecksum{1, 1, generateNewTracebackID()}, 18},
		{ErrorMismatchedChecksum{1, math.MaxUint32, generateNewTracebackID()}, 18},
		{ErrorMismatchedChecksum{math.MaxUint32, 1, generateNewTracebackID()}, 18},
		{ErrorMismatchedChecksum{math.MaxUint32, math.MaxUint32, generateNewTracebackID()}, 18},
		{ErrorMismatchedChecksum{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

