func TestInternalError_IsValid(t *testing.T) {
	tests := []struct {
		e    ErrorInternalError
		want bool
	}{
		{
			ErrorInternalError{nil, uuid.UUID([16]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01})},
			false,
		},
		{
			ErrorInternalError{errors.New(""), uuid.UUID([16]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02})},
			true,
		},
		{
			ErrorInternalError{errors.New("some-error"), uuid.UUID([16]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03})},
			true,
		},
		{
			ErrorInternalError{},
			false,
		},
		{
			ErrorInternalError{NewErrorUnsupportedCommand(command.Code(10)), generateNewTracebackID()},
			false,
		},
		{
			ErrorInternalError{NewErrorUnsupportedCommand(command.Read), generateNewTracebackID()},
			false,
		},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test IsValid: %v", tt.e),
			func(t *testing.T) {
				if got := tt.e.IsValid(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

func TestInternalError_Encode(t *testing.T) {
	tests := []struct {
		e    ErrorInternalError
		want []byte
	}{
		{
			ErrorInternalError{nil, uuid.UUID([16]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01})},
			[]byte{0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01},
		},
		{
			ErrorInternalError{errors.New(""), uuid.UUID([16]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02})},
			[]byte{0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02},
		},
		{
			ErrorInternalError{errors.New("some-error"), uuid.UUID([16]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03})},
			[]byte{0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03},
		},
		{
			ErrorInternalError{},
			[]byte{0x00, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
		},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				buf := buffer.Mock{}
				buf.Preallocate(tt.e.Size())

				tt.e.Encode(&buf)

				if got := buf.Bytes(); !bytes.Equal(got, tt.want) {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}
