func TestUnexpectedCommand_Size(t *testing.T) {
	tests := []struct {
		e    ErrorUnexpectedCommand
		want int
	}{
		{ErrorUnexpectedCommand{command.Answer, command.Handshake, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Handshake, command.Read, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Read, command.Write, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Write, command.Delete, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Delete, command.Ping, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Ping, command.Batch, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Batch, command.Answer, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Code(7), command.Code(10), generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Code(255), command.Answer, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{command.Answer, command.Answer, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{}, 19},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

