func TestUnexpectedCommand_Size(t *testing.T) {
	tests := []struct {
		e    ErrorUnexpectedCommand
		want int
	}{
		{ErrorUnexpectedCommand{fields.Answer, fields.Handshake, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Handshake, fields.Read, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Read, fields.Write, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Write, fields.Delete, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Delete, fields.Ping, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Ping, fields.Batch, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Batch, fields.Answer, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Command(7), fields.Command(10), generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Command(255), fields.Answer, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{fields.Answer, fields.Answer, generateNewTracebackID()}, 19},
		{ErrorUnexpectedCommand{}, 19},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

