func TestInvalidRequestID_Size(t *testing.T) {
	tests := []struct {
		e    ErrorInvalidRequestID
		want int
	}{
		{ErrorInvalidRequestID{command.Answer, 0, generateNewTracebackID()}, 18},
		{ErrorInvalidRequestID{command.Batch, 1, generateNewTracebackID()}, 18},
		{ErrorInvalidRequestID{command.Handshake, math.MaxUint32, generateNewTracebackID()}, 18},
		{ErrorInvalidRequestID{command.Code(10), 1, generateNewTracebackID()}, 18},
		{ErrorInvalidRequestID{command.Code(11), math.MaxUint32, generateNewTracebackID()}, 18},
		{ErrorInvalidRequestID{command.Code(255), math.MaxUint32, generateNewTracebackID()}, 18},
		{ErrorInvalidRequestID{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

