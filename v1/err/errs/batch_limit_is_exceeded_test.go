func TestBatchLimitIsExceeded_Size(t *testing.T) {
	tests := []struct {
		e    ErrorBatchLimitIsExceeded
		want int
	}{
		{ErrorBatchLimitIsExceeded{0, 1, generateNewTracebackID()}, 22},
		{ErrorBatchLimitIsExceeded{1, 0, generateNewTracebackID()}, 22},
		{ErrorBatchLimitIsExceeded{1, 1, generateNewTracebackID()}, 22},
		{ErrorBatchLimitIsExceeded{1, math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorBatchLimitIsExceeded{math.MaxUint32, 1, generateNewTracebackID()}, 22},
		{ErrorBatchLimitIsExceeded{math.MaxUint32, math.MaxUint32, generateNewTracebackID()}, 22},
		{ErrorBatchLimitIsExceeded{}, 22},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

