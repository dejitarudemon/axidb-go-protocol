func TestProhibitedCompression_Size(t *testing.T) {
	tests := []struct {
		e    ErrorProhibitedCompression
		want int
	}{
		{ErrorProhibitedCompression{compression.None, command.Handshake, generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{compression.Lz4, command.Read, generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{compression.Zstd, command.Write, generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{compression.Code(4), command.Delete, generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{compression.None, command.Code(4), generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{compression.Code(5), command.Code(5), generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{compression.Code(255), command.Code(255), generateNewTracebackID()}, 18},
		{ErrorProhibitedCompression{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

