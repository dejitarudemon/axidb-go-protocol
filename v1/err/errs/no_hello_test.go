func TestNoHello_Size(t *testing.T) {
	tests := []struct {
		e    ErrorNoHello
		want int
	}{
		{ErrorNoHello{generateNewTracebackID()}, 18},
		{ErrorNoHello{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

