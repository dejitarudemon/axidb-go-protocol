func TestUnsupportedCompression_Size(t *testing.T) {
	tests := []struct {
		e    ErrorUnsupportedCompression
		want int
	}{
		{ErrorUnsupportedCompression{compression.Lz4, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCompression{compression.None, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCompression{compression.Zstd, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCompression{compression.Code(3), generateNewTracebackID()}, 18},
		{ErrorUnsupportedCompression{compression.Code(255), generateNewTracebackID()}, 18},
		{ErrorUnsupportedCompression{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

