func TestUnsupportedCommand_Size(t *testing.T) {
	tests := []struct {
		e    ErrorUnsupportedCommand
		want int
	}{
		{ErrorUnsupportedCommand{fields.Answer, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Handshake, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Read, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Write, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Delete, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Ping, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Batch, generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Command(7), generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{fields.Command(8), generateNewTracebackID()}, 18},
		{ErrorUnsupportedCommand{}, 18},
	}

	for _, tt := range tests {
		t.Run(
			fmt.Sprintf("Test Size: %v", tt),
			func(t *testing.T) {
				if got := tt.e.Size(); got != tt.want {
					t.Fatalf("got %v, want %v", got, tt.want)
				}
			},
		)
	}
}

