func TestFrame_Size(t *testing.T) {
	for i, tt := range testsSpecs {
		t.Run(
			fmt.Sprintf("TestFrame_Size %v", i),
			func(t *testing.T) {
				if got := tt.decoded.Size(); got != tt.size {
					t.Errorf("frame Size() failure: got %v want %v", got, tt.size)
				}
			},
		)
	}
}

