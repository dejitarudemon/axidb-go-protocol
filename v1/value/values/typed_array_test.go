package values

import (
	"testing"

	"github.com/dejitarudemon/axidb-go-protocol/v1/fields"
	"github.com/dejitarudemon/axidb-go-protocol/v1/value"
)

func TestTypedArray(t *testing.T) {
	tests := []struct {
		name    string
		v       TypedArray
		want    []byte
		wantErr bool
	}{
		{
			"nil elems",
			TypedArray{ElemType: fields.Int},
			[]byte{0x00, 0x00, 0x00, 0x00, 0x03},
			false,
		},
		{
			"empty",
			TypedArray{ElemType: fields.Int, Elems: []value.V{}},
			[]byte{0x00, 0x00, 0x00, 0x00, 0x03},
			false,
		},
		{
			"one int",
			TypedArray{ElemType: fields.Int, Elems: []value.V{Int(1)}},
			[]byte{
				0x00, 0x00, 0x00, 0x01, 0x03,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
			},
			false,
		},
		{
			"two ints",
			TypedArray{ElemType: fields.Int, Elems: []value.V{Int(1), Int(2)}},
			[]byte{
				0x00, 0x00, 0x00, 0x02, 0x03,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02,
			},
			false,
		},
		{
			"valid json",
			TypedArray{ElemType: fields.JSON, Elems: []value.V{JSON(`{}`)}},
			[]byte{
				0x00, 0x00, 0x00, 0x01, 0x07,
				0x00, 0x00, 0x00, 0x02, 0x7B, 0x7D,
			},
			false,
		},
		{
			"only nil",
			TypedArray{ElemType: fields.Int, Elems: []value.V{nil}},
			[]byte{0x00, 0x00, 0x00, 0x00, 0x03},
			true,
		},
		{
			"nil between ints",
			TypedArray{ElemType: fields.Int, Elems: []value.V{Int(1), nil, Int(2)}},
			[]byte{
				0x00, 0x00, 0x00, 0x02, 0x03,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02,
			},
			true,
		},
		{
			"float in int array",
			TypedArray{ElemType: fields.Int, Elems: []value.V{Int(1), Float(1)}},
			[]byte{
				0x00, 0x00, 0x00, 0x02, 0x03,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x3F, 0xF0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			},
			true,
		},
		{
			"bytes in int array",
			TypedArray{ElemType: fields.Int, Elems: []value.V{Int(1), Bytes([]byte{0x01, 0x02, 0x03})}},
			[]byte{
				0x00, 0x00, 0x00, 0x02, 0x03,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x03, 0x01, 0x02, 0x03,
			},
			true,
		},
		{
			"invalid elem",
			TypedArray{ElemType: fields.JSON, Elems: []value.V{JSON([]byte{0x01, 0x02, 0x03})}},
			[]byte{
				0x00, 0x00, 0x00, 0x01, 0x07,
				0x00, 0x00, 0x00, 0x03, 0x01, 0x02, 0x03,
			},
			true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assertValue(t, tt.v, fields.TypedArray, tt.want, tt.wantErr)
		})
	}
}
