package values

import (
	"testing"

	"github.com/dejitarudemon/axidb-go-protocol/v1/fields"
)

func TestUntypedArray(t *testing.T) {
	tests := []struct {
		name    string
		v       UntypedArray
		want    []byte
		wantErr bool
	}{
		{
			"nil",
			UntypedArray(nil),
			[]byte{0x00, 0x00, 0x00, 0x00},
			false,
		},
		{
			"empty",
			UntypedArray{},
			[]byte{0x00, 0x00, 0x00, 0x00},
			false,
		},
		{
			"one int",
			UntypedArray{Int(1)},
			[]byte{
				0x00, 0x00, 0x00, 0x01,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
			},
			false,
		},
		{
			"two ints",
			UntypedArray{Int(1), Int(2)},
			[]byte{
				0x00, 0x00, 0x00, 0x02,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02,
			},
			false,
		},
		{
			"int and float",
			UntypedArray{Int(1), Float(1)},
			[]byte{
				0x00, 0x00, 0x00, 0x02,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x05, 0x3F, 0xF0, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			},
			false,
		},
		{
			"int and bytes",
			UntypedArray{Int(1), Bytes([]byte{0x01, 0x02, 0x03})},
			[]byte{
				0x00, 0x00, 0x00, 0x02,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x00, 0x03, 0x01, 0x02, 0x03,
			},
			false,
		},
		{
			"only nil",
			UntypedArray{nil},
			[]byte{0x00, 0x00, 0x00, 0x00},
			true,
		},
		{
			"nil after int",
			UntypedArray{Int(1), nil},
			[]byte{
				0x00, 0x00, 0x00, 0x01,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
			},
			true,
		},
		{
			"invalid elem",
			UntypedArray{Int(1), JSON([]byte{0x01, 0x02, 0x03})},
			[]byte{
				0x00, 0x00, 0x00, 0x02,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x07, 0x00, 0x00, 0x00, 0x03, 0x01, 0x02, 0x03,
			},
			true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assertValue(t, tt.v, fields.UntypedArray, tt.want, tt.wantErr)
		})
	}
}
