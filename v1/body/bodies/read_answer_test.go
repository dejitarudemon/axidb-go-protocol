package bodies

import (
	"testing"

	"github.com/dejitarudemon/axidb-go-protocol/v1/fields"
	"github.com/dejitarudemon/axidb-go-protocol/v1/value/values"
)

func TestReadAnswer(t *testing.T) {
	tests := []struct {
		name    string
		b       ReadAnswer
		want    []byte
		wantErr bool
	}{
		{"nil value", ReadAnswer{}, []byte{0x01, 0x02}, true},
		{
			"int value",
			ReadAnswer{values.Int(0)},
			[]byte{0x01, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
			false,
		},
		{
			"bytes value",
			ReadAnswer{values.Bytes("data")},
			[]byte{0x01, 0x02, 0x00, 0x00, 0x00, 0x00, 0x04, 0x64, 0x61, 0x74, 0x61},
			false,
		},
		{
			"string value",
			ReadAnswer{values.String("some-data")},
			[]byte{
				0x01, 0x02, 0x06, 0x00, 0x00, 0x00, 0x09,
				0x73, 0x6F, 0x6D, 0x65, 0x2D, 0x64, 0x61, 0x74, 0x61,
			},
			false,
		},
		{
			"untyped array value",
			ReadAnswer{values.UntypedArray{
				values.Int(1),
				values.String("hello world"),
				values.Float(2.1),
			}},
			[]byte{
				0x01, 0x02, 0x02, 0x00, 0x00, 0x00, 0x03,
				0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
				0x06, 0x00, 0x00, 0x00, 0x0B, 0x68, 0x65, 0x6C, 0x6C, 0x6F, 0x20, 0x77, 0x6F, 0x72, 0x6C, 0x64,
				0x05, 0x40, 0x00, 0xCC, 0xCC, 0xCC, 0xCC, 0xCC, 0xCD,
			},
			false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assertAnswer(t, tt.b, fields.Read, tt.want, tt.wantErr)
		})
	}
}
